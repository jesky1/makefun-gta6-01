// A tiny seeded random generator (splitmix-flavoured). One stream drives
// the whole simulation, so a seed plus an input sequence fully determines
// a run — that is what makes the story test and the screenshots repeatable.

export function createRandom(seed) {
  let state = (seed >>> 0) || 0x85ebca6b;
  function next() {
    state = (state + 0x9e3779b9) >>> 0;
    let z = state;
    z = Math.imul(z ^ (z >>> 16), 0x21f0aaad);
    z = Math.imul(z ^ (z >>> 15), 0x735a2d97);
    z ^= z >>> 15;
    return (z >>> 0) / 4294967296;
  }
  return {
    next,
    range(min, max) { return min + next() * (max - min); },
    int(min, max) { return Math.floor(min + next() * (max - min + 1)); },
    pick(list) { return list[Math.floor(next() * list.length) % list.length]; },
    chance(p) { return next() < p; },
  };
}
